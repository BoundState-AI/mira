class SectionContent(BaseModel):
    """
    Pre-computed content for a document section.

    All logic is computed here - templates only insert values.
    """

    section_id: str
    """Unique section identifier."""

    section_title: str
    """Human-readable title."""

    section_number: str = ""
    """Document section number (e.g., '3.2.1')."""

    text_content: str = ""
    """Pre-formatted text content."""

    table_content: list[dict[str, Any]] = Field(default_factory=list)
    """Table rows as dicts (column_name -> value)."""

    bullet_points: list[str] = Field(default_factory=list)
    """List items."""

    subsections: list[SectionContent] = Field(default_factory=list)
    """Nested subsections."""

    metadata: dict[str, Any] = Field(default_factory=dict)
    """Additional metadata for rendering."""

    is_empty: bool = False
    """Whether this section has no content."""

    model_config = {"extra": "forbid", "populate_by_name": True}


class SectionBuilder:
    """
    Builds pre-computed section content from session state.

    Fran Fix #9: All decision logic happens here, NOT in templates.
    Templates are deliberately dumb - they only:
    - Insert values: {{ section.text_content }}
    - Iterate: {% for row in section.table_content %}
    - Check presence: {% if section.content %}

    Forbidden in templates: {% if material.o2_pct > 23.5 %}
    """

    def __init__(
        self,
        session: PlanGeneratorSession,
        policy_pack: Optional[PolicyPack] = None,
    ):
        """
        Initialize section builder.

        Args:
            session: Plan generator session.
            policy_pack: Optional policy pack.
        """
        self._session = session
        self._policy = policy_pack or create_default_policy_pack()

    def build_cover_section(self) -> SectionContent:
        """Build cover page section."""
        return SectionContent(
            section_id="cover",
            section_title="Materials and Processes Plan",
            text_content=f"""
MATERIALS AND PROCESSES PLAN

Program: {self._session.program_name or 'TBD'}
Phase: {self._session.program_phase or 'TBD'}
Document Date: {datetime.now().strftime('%Y-%m-%d')}

Generated by: M&P Plan Generator V2
Session ID: {self._session.session_id}
            """.strip(),
            metadata={
                "program_name": self._session.program_name,
                "program_phase": self._session.program_phase,
                "session_id": self._session.session_id,
                "generated_at": datetime.now().isoformat(),
            },
        )

    def build_scope_section(self) -> SectionContent:
        """Build Section 1.0 Scope and Purpose."""
        env_names = [e.name for e in self._session.environments] or ["TBD"]
        mat_count = len(self._session.materials)

        return SectionContent(
            section_id="scope",
            section_title="Scope and Purpose",
            section_number="1.0",
            text_content=f"This Materials and Processes (M&P) Plan documents the materials selection, evaluation, and compliance status for the {self._session.program_name or 'TBD'} program.",
            subsections=[
                SectionContent(
                    section_id="scope_purpose",
                    section_title="Purpose",
                    section_number="1.1",
                    text_content="This document provides a comprehensive record of materials used in the program, their test data, applicability to NASA Materials and Processes Requirements (MPRs), and any nonconformances requiring disposition.",
                ),
                SectionContent(
                    section_id="scope_applicable",
                    section_title="Applicable Documents",
                    section_number="1.2",
                    bullet_points=[
                        "NASA-STD-6016 - Standard Materials and Processes Requirements for Spacecraft",
                        "MAPTIS - Materials and Processes Technical Information System",
                        "Program-specific M&P requirements (as applicable)",
                    ],
                ),
                SectionContent(
                    section_id="scope_summary",
                    section_title="Document Summary",
                    section_number="1.3",
                    bullet_points=[
                        f"Environments covered: {', '.join(env_names)}",
                        f"Materials evaluated: {mat_count}",
                        f"Nonconformances identified: {len(self._session.nonconformances)}",
                        f"Closures documented: {len(self._session.closure_decisions)}",
                        f"Open gaps tracked: {len(self._session.accepted_open_gaps)}",
                    ],
                ),
            ],
        )

    def build_environment_section(self) -> SectionContent:
        """Build environment definitions section."""
        if not self._session.environments:
            return SectionContent(
                section_id="environments",
                section_title="Environment Definitions",
                section_number="2.0",
                text_content="No environments defined.",
                is_empty=True,
            )

        table_rows = []
        for env in self._session.environments:
            # Pre-compute all display values
            temp_range = f"{env.temp_range_c[0]}°C to {env.temp_range_c[1]}°C"
            o2_status = "Elevated O2" if env.o2_pct > 23.5 else "Standard"

            table_rows.append({
                "name": env.name,
                "o2_pct": f"{env.o2_pct}%",
                "o2_status": o2_status,
                "pressure_psia": f"{env.pressure_psia} psia",
                "temp_range": temp_range,
                "habitable": "Yes" if env.habitable else "No",
                "vacuum_exposure": "Yes" if env.vacuum_exposure else "No",
                "lunar_dust": "Yes" if env.lunar_dust else "No",
                "phase": env.phase,
            })

        return SectionContent(
            section_id="environments",
            section_title="Environment Definitions",
            section_number="2.0",
            text_content=f"This plan covers {len(self._session.environments)} operating environment(s).",
            table_content=table_rows,
        )

    def build_materials_section(self) -> SectionContent:
        """Build materials list section."""
        if not self._session.materials:
            return SectionContent(
                section_id="materials",
                section_title="Materials List",
                section_number="3.0",
                text_content="No materials defined.",
                is_empty=True,
            )

        table_rows = []
        for material in self._session.materials:
            # Pre-compute display values
            mass_str = f"{material.mass_g} g" if material.mass_g else "TBD"
            area_str = f"{material.surface_area_cm2} cm²" if material.surface_area_cm2 else "TBD"

            # Get resolution if available
            resolution = self._session.get_resolution(material.id)
            flam_rating = resolution.flam_rating if resolution else "Not Resolved"
            test_o2 = f"{resolution.test_o2_pct}%" if resolution and resolution.test_o2_pct else "N/A"

            table_rows.append({
                "name": material.name,
                "application": material.application,
                "maptis_code": material.maptis_code or "TBD",
                "quantity": material.quantity,
                "mass": mass_str,
                "surface_area": area_str,
                "flam_rating": flam_rating,
                "test_o2_pct": test_o2,
            })

        return SectionContent(
            section_id="materials",
            section_title="Materials List",
            section_number="3.0",
            text_content=f"This plan covers {len(self._session.materials)} material(s).",
            table_content=table_rows,
        )

    def build_test_deltas_section(self) -> SectionContent:
        """Build Test Condition Deltas section - critical for reviewer awareness."""
        deltas_table = []
        deltas_outside_envelope = []

        for material in self._session.materials:
            resolution = self._session.get_resolution(material.id)
            if not resolution:
                continue

            for env in self._session.environments:
                # O2 Delta
                if resolution.test_o2_pct is not None:
                    o2_delta = env.o2_pct - resolution.test_o2_pct
                    within = o2_delta <= 0  # Use O2 <= Test O2 is OK

                    delta_row = {
                        "material": material.name,
                        "environment": env.name,
                        "parameter": "O2 %",
                        "test_value": f"{resolution.test_o2_pct}%",
                        "use_value": f"{env.o2_pct}%",
                        "delta": f"{o2_delta:+.1f}%",
                        "status": "Within Envelope" if within else "OUTSIDE ENVELOPE",
                    }
                    deltas_table.append(delta_row)

                    if not within:
                        deltas_outside_envelope.append({
                            "material": material.name,
                            "environment": env.name,
                            "issue": f"Use O2 ({env.o2_pct}%) exceeds test O2 ({resolution.test_o2_pct}%)",
                            "rationale_needed": "Requires justification for use in elevated O2 environment",
                        })

                # Pressure Delta (if available)
                if resolution.test_pressure_psia is not None:
                    p_delta = env.pressure_psia - resolution.test_pressure_psia
                    within = abs(p_delta) <= 2.0  # 2 psia tolerance

                    delta_row = {
                        "material": material.name,
                        "environment": env.name,
                        "parameter": "Pressure",
                        "test_value": f"{resolution.test_pressure_psia} psia",
                        "use_value": f"{env.pressure_psia} psia",
                        "delta": f"{p_delta:+.1f} psia",
                        "status": "Within Envelope" if within else "OUTSIDE ENVELOPE",
                    }
                    deltas_table.append(delta_row)

        # Build subsections for items outside envelope
        subsections = []
        if deltas_outside_envelope:
            outside_table = []
            for item in deltas_outside_envelope:
                outside_table.append({
                    "material": item["material"],
                    "environment": item["environment"],
                    "issue": item["issue"],
                    "action_required": item["rationale_needed"],
                })

            subsections.append(SectionContent(
                section_id="deltas_attention",
                section_title="Items Requiring Attention",
                section_number="4.1",
                text_content=f"The following {len(deltas_outside_envelope)} item(s) have use conditions outside the tested envelope and require rationale or additional testing:",
                table_content=outside_table,
            ))

        if not deltas_table:
            return SectionContent(
                section_id="test_deltas",
                section_title="Test Condition Deltas",
                section_number="4.0",
                text_content="No test data available for delta analysis.",
                is_empty=True,
            )

        return SectionContent(
            section_id="test_deltas",
            section_title="Test Condition Deltas",
            section_number="4.0",
            text_content="The following table compares test conditions to actual use conditions. Items with use conditions exceeding test envelope require rationale.",
            table_content=deltas_table,
            subsections=subsections,
            metadata={
                "total_deltas": len(deltas_table),
                "outside_envelope": len(deltas_outside_envelope),
            },
        )

    def build_applicability_section(self) -> SectionContent:
        """Build MPR applicability section."""
        if not self._session.applicability_matrix:
            return SectionContent(
                section_id="applicability",
                section_title="MPR Applicability",
                section_number="5.0",
                text_content="Applicability matrix not yet computed.",
                is_empty=True,
            )

        # Build applicability summary
        applicable_mprs = set()
        not_applicable_mprs = set()

        for key, mprs in self._session.applicability_matrix.items():
            for mpr_id, decision in mprs.items():
                status = decision.get("status", "unknown")
                if status == "applicable":
                    applicable_mprs.add(mpr_id)
                elif status == "not_applicable_by_condition":
                    not_applicable_mprs.add(mpr_id)

        bullet_points = [
            f"Applicable MPRs: {', '.join(sorted(applicable_mprs)) or 'None'}",
            f"Not Applicable: {', '.join(sorted(not_applicable_mprs)) or 'None'}",
        ]

        return SectionContent(
            section_id="applicability",
            section_title="MPR Applicability",
            section_number="5.0",
            text_content=f"Based on the defined environments and materials, the following MPR applicability has been determined.",
            bullet_points=bullet_points,
            metadata={
                "applicable_count": len(applicable_mprs),
                "not_applicable_count": len(not_applicable_mprs),
            },
        )

    def build_nonconformances_section(self) -> SectionContent:
        """Build nonconformances section."""
        if not self._session.nonconformances:
            return SectionContent(
                section_id="nonconformances",
                section_title="Nonconformances",
                section_number="6.0",
                text_content="No nonconformances identified. All materials meet applicable requirements.",
                is_empty=True,
            )

        table_rows = []
        for nc in self._session.nonconformances:
            material = self._session.get_material(nc.material_id)
            env = self._session.get_environment(nc.environment_id)

            # Get closure status
            closure = next(
                (c for c in self._session.closure_decisions if c.gap_id == nc.nonconformance_id),
                None
            )
            accepted = next(
                (a for a in self._session.accepted_open_gaps if a.gap_id == nc.nonconformance_id),
                None
            )

            if closure:
                status = f"Closed: {closure.selected_path}"
            elif accepted:
                status = "Accepted Open"
            else:
                status = "Open"

            table_rows.append({
                "id": nc.nonconformance_id[:8],
                "material": material.name if material else nc.material_id,
                "environment": env.name if env else nc.environment_id,
                "gap_type": nc.gap_type.value.upper(),
                "failing_requirement": nc.failing_requirement,
                "failing_value": nc.failing_value,
                "required_value": nc.required_value,
                "status": status,
                "severity": nc.severity.value if nc.severity else "medium",
            })

        return SectionContent(
            section_id="nonconformances",
            section_title="Nonconformances",
            section_number="6.0",
            text_content=f"The following {len(self._session.nonconformances)} nonconformance(s) were identified.",
            table_content=table_rows,
        )

    def build_closures_section(self) -> SectionContent:
        """Build closure decisions section."""
        if not self._session.closure_decisions:
            return SectionContent(
                section_id="closures",
                section_title="Closure Decisions",
                section_number="7.0",
                text_content="No closure decisions recorded.",
                is_empty=True,
            )

        table_rows = []
        for closure in self._session.closure_decisions:
            # Find the related nonconformance
            nc = next(
                (n for n in self._session.nonconformances if n.nonconformance_id == closure.gap_id),
                None
            )
            material_name = "Unknown"
            if nc:
                material = self._session.get_material(nc.material_id)
                material_name = material.name if material else nc.material_id

            table_rows.append({
                "gap_id": closure.gap_id[:8],
                "material": material_name,
                "selected_path": closure.selected_path,
                "rationale": closure.decision_rationale,
                "decided_by": closure.decided_by,
                "decided_at": closure.decided_at.strftime("%Y-%m-%d") if closure.decided_at else "N/A",
            })

        return SectionContent(
            section_id="closures",
            section_title="Closure Decisions",
            section_number="7.0",
            text_content=f"The following {len(self._session.closure_decisions)} closure decision(s) were made.",
            table_content=table_rows,
        )

    def build_open_gaps_section(self) -> SectionContent:
        """Build accepted open gaps section."""
        if not self._session.accepted_open_gaps:
            return SectionContent(
                section_id="open_gaps",
                section_title="Accepted Open Gaps",
                section_number="8.0",
                text_content="No gaps accepted as open.",
                is_empty=True,
            )

        table_rows = []
        for gap in self._session.accepted_open_gaps:
            table_rows.append({
                "gap_id": gap.gap_id[:8],
                "owner": gap.owner,
                "due_date": gap.due_date.strftime("%Y-%m-%d") if gap.due_date else "TBD",
                "risk_statement": gap.risk_statement,
                "rationale": gap.acceptance_rationale,
                "accepted_by": gap.accepted_by,
            })

        return SectionContent(
            section_id="open_gaps",
            section_title="Accepted Open Gaps",
            section_number="8.0",
            text_content=f"The following {len(self._session.accepted_open_gaps)} gap(s) are accepted as open with tracking.",
            table_content=table_rows,
        )

    def build_minor_quantity_section(self) -> SectionContent:
        """Build minor quantity aggregation section."""
        if not self._session.minor_quantity_aggregation:
            return SectionContent(
                section_id="minor_qty",
                section_title="Minor Quantity Analysis",
                section_number="9.0",
                text_content="No minor quantity analysis performed.",
                is_empty=True,
            )

        agg = self._session.minor_quantity_aggregation
        table_rows = []

        for group in agg.groups:
            status = "Qualifies" if group.eligible else "Exceeds Limit"
            table_rows.append({
                "environment": group.environment_id,
                "ignition_class": group.ignition_source_class,
                "total_mass_g": f"{group.total_mass_g:.2f} g",
                "total_area_cm2": f"{group.total_surface_area_cm2:.2f} cm²",
                "material_count": len(group.material_ids),
                "status": status,
                "rationale": group.eligibility_rationale[:50] if group.eligibility_rationale else "",
            })

        return SectionContent(
            section_id="minor_qty",
            section_title="Minor Quantity Analysis",
            section_number="9.0",
            text_content="Per MPR 44(c), materials may qualify for minor quantity exception when aggregated totals remain below thresholds.",
            table_content=table_rows,
            metadata={
                "total_groups": len(agg.groups),
                "qualifying_groups": len([g for g in agg.groups if g.eligible]),
            },
        )

    def build_all_sections(self) -> list[SectionContent]:
        """Build all document sections."""
        return [
            self.build_cover_section(),
            self.build_scope_section(),           # 1.0 Scope and Purpose
            self.build_environment_section(),      # 2.0 Environment Definitions
            self.build_materials_section(),        # 3.0 Materials List
            self.build_test_deltas_section(),      # 4.0 Test Condition Deltas
            self.build_applicability_section(),    # 5.0 MPR Applicability
            self.build_nonconformances_section(),  # 6.0 Nonconformances
            self.build_closures_section(),         # 7.0 Closure Decisions
            self.build_open_gaps_section(),        # 8.0 Accepted Open Gaps
            self.build_minor_quantity_section(),   # 9.0 Minor Quantity Analysis
        ]


def build_all_sections(
    session: PlanGeneratorSession,
    policy_pack: Optional[PolicyPack] = None,
) -> list[SectionContent]:
    """
    Build all sections for a session.

    Args:
        session: Plan generator session.
        policy_pack: Optional policy pack.

    Returns:
        List of pre-computed section contents.
    """
    builder = SectionBuilder(session, policy_pack)
    return builder.build_all_sections()
