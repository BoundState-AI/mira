"""
Evaluate PDF Audit Confidence
=============================

Evaluates completed manual audit results from the CSV generated by
`013_generate_pdf_audit_sample.py`.

Computes:
  - audited count
  - failure rate
  - Wilson confidence interval
  - pass/fail vs target max defect rate
  - recommended additional sample size

Usage
-----
    py -3 mira/mua/v7/migrations/014_evaluate_pdf_audit_confidence.py \\
      --audit-csv <path_to_completed_sample.csv> \\
      --population-size 5650 \\
      --confidence 0.95 \\
      --target-max-defect 0.05
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from datetime import datetime, timezone
from pathlib import Path
from statistics import NormalDist


TRUE_SET = {"1", "true", "t", "yes", "y", "pass", "passed"}
FALSE_SET = {"0", "false", "f", "no", "n", "fail", "failed"}


def _parse_bool_like(value: str):
    v = (value or "").strip().lower()
    if not v:
        return None
    if v in TRUE_SET:
        return True
    if v in FALSE_SET:
        return False
    return None


def _wilson_interval(k_fail: int, n: int, confidence: float) -> tuple[float, float, float]:
    if n <= 0:
        return (0.0, 1.0, 0.0)
    z = NormalDist().inv_cdf(0.5 + confidence / 2.0)
    p = k_fail / n
    denom = 1.0 + (z * z / n)
    center = (p + (z * z) / (2.0 * n)) / denom
    half = (z * math.sqrt((p * (1.0 - p) + (z * z) / (4.0 * n)) / n)) / denom
    lo = max(0.0, center - half)
    hi = min(1.0, center + half)
    return lo, hi, p


def _required_n(population_n: int, confidence: float, margin: float, p_estimate: float) -> int:
    if population_n <= 0:
        return 0
    z = NormalDist().inv_cdf(0.5 + confidence / 2.0)
    n0 = (z * z * p_estimate * (1.0 - p_estimate)) / (margin * margin)
    n = n0 / (1.0 + ((n0 - 1.0) / population_n))
    return max(1, min(population_n, math.ceil(n)))


def main() -> None:
    parser = argparse.ArgumentParser(description="Evaluate confidence from completed PDF audit sample.")
    parser.add_argument("--audit-csv", required=True, help="Path to completed audit CSV.")
    parser.add_argument("--population-size", type=int, required=True, help="Population size N.")
    parser.add_argument("--confidence", type=float, default=0.95, help="Confidence level.")
    parser.add_argument("--target-max-defect", type=float, default=0.05, help="Max acceptable defect rate.")
    parser.add_argument("--target-margin", type=float, default=0.05, help="Planning margin for additional sample size.")
    args = parser.parse_args()

    audit_csv = Path(args.audit_csv)
    if not audit_csv.exists():
        raise SystemExit(f"Audit CSV not found: {audit_csv}")

    n_total = 0
    n_scored = 0
    fails = 0
    passes = 0

    with audit_csv.open("r", newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            n_total += 1
            decision = _parse_bool_like(str(row.get("audit_pass", "")))
            if decision is None:
                continue
            n_scored += 1
            if decision:
                passes += 1
            else:
                fails += 1

    lo, hi, p_hat = _wilson_interval(fails, n_scored, args.confidence)
    meets_target = (hi <= args.target_max_defect)

    # Additional sample planning uses worst-case variance (p=0.5) so required
    # sample size remains statistically conservative and stable.
    p_plan = 0.5
    required_n = _required_n(
        population_n=args.population_size,
        confidence=args.confidence,
        margin=args.target_margin,
        p_estimate=p_plan,
    )
    additional_needed = max(0, required_n - n_scored)

    out = {
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "audit_csv": str(audit_csv),
        "population_size": args.population_size,
        "confidence": args.confidence,
        "target_max_defect": args.target_max_defect,
        "target_margin": args.target_margin,
        "rows_in_csv": n_total,
        "rows_scored": n_scored,
        "passes": passes,
        "fails": fails,
        "observed_defect_rate": p_hat,
        "wilson_lower": lo,
        "wilson_upper": hi,
        "meets_target": meets_target,
        "recommended_required_n": required_n,
        "recommended_additional_n": additional_needed,
    }

    out_dir = Path(__file__).resolve().parent / "reports"
    out_dir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    out_file = out_dir / f"014_audit_confidence_{stamp}.json"
    out_file.write_text(json.dumps(out, indent=2), encoding="utf-8")

    print("=" * 72)
    print("AUDIT CONFIDENCE EVALUATION")
    print("=" * 72)
    print(f"Audit CSV:                 {audit_csv}")
    print(f"Rows scored:               {n_scored} / {n_total}")
    print(f"Observed defect rate:      {p_hat:.4f}")
    print(f"Wilson {args.confidence:.3f} CI:       [{lo:.4f}, {hi:.4f}]")
    print(f"Target max defect:         {args.target_max_defect:.4f}")
    print(f"Meets target:              {meets_target}")
    print(f"Recommended total n:       {required_n}")
    print(f"Recommended additional n:  {additional_needed}")
    print(f"Report:                    {out_file}")


if __name__ == "__main__":
    main()
